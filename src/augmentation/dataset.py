"""Build synthetic datasets from GAN-generated sequences."""

import json
import torch
from tqdm.auto import tqdm

from src.augmentation.gan import Generator
from src.augmentation.decoder import EmbeddingDecoder
from src.augmentation.pseudo_label import pseudo_label


def build_synthetic_dataset(
    n_chunks: int,
    chunk_len: int,
    generator: Generator,
    decoder: EmbeddingDecoder,
    model,
    device: str,
    save_path: str,
    latent_dim: int = 128,
) -> dict:
    """Generate n_chunks synthetic sequences of length chunk_len.

    Each sequence is generated by sampling chunk_len noise vectors,
    running them through the generator, decoding each embedding to an
    amino acid, then pseudo-labelling the resulting string.

    Returns:
        {"sequences": list[str], "disorder region": list[list[int]]}
        Also saves this dict as JSON to save_path.
    """
    generator.eval()
    sequences = []

    with torch.no_grad():
        for _ in tqdm(range(n_chunks), desc="Generating sequences"):
            z = torch.randn(chunk_len, latent_dim).to(device)
            embs = generator(z)          # (chunk_len, 1024)
            seq = decoder.decode_sequence(embs.cpu())
            if len(seq) >= 2:
                sequences.append(seq)

    labels = pseudo_label(sequences, model)

    data = {"sequences": sequences, "disorder region": labels}
    with open(save_path, "w") as f:
        json.dump(data, f)

    return data
